"""Build standard P0 result files from legacy UrbanHeatOpt outputs."""

from __future__ import annotations

from dataclasses import dataclass
import json
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from urbanheatopt.data.validation.inputs import validate_case_inputs


@dataclass(frozen=True)
class StandardResultExport:
    """Paths written by the standard P0 exporter."""

    output_dir: Path
    metadata_json: Path
    assumptions_yaml: Path
    connections_csv: Path
    capacities_csv: Path
    pipes_csv: Path
    dispatch_csv: Path
    costs_csv: Path
    solver_report_json: Path
    balance_check_csv: Path
    cost_check_csv: Path
    qa_report_json: Path


def _read_legacy_csv(path: Path) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f"Missing legacy result file: {path}")
    return pd.read_csv(path, sep=";")


def _read_legacy_dispatch(path: Path, timestamp_hour_map: pd.DataFrame) -> pd.DataFrame:
    raw = _read_legacy_csv(path)
    if raw.empty:
        raise ValueError(f"Legacy dispatch file is empty: {path}")
    id_column = raw.columns[0]
    long = raw.melt(id_vars=id_column, var_name="legacy_hour", value_name="heat_kW")
    long["legacy_hour"] = pd.to_numeric(long["legacy_hour"], errors="raise").astype(int)
    long["heat_kW"] = pd.to_numeric(long["heat_kW"], errors="raise").astype(float)
    hour_map = timestamp_hour_map.copy()
    hour_map["hour"] = pd.to_numeric(hour_map["hour"], errors="raise").astype(int)
    merged = long.merge(hour_map, left_on="legacy_hour", right_on="hour", how="left", validate="many_to_one")
    if merged["timestamp"].isna().any():
        missing = sorted(merged.loc[merged["timestamp"].isna(), "legacy_hour"].unique().tolist())
        raise ValueError(f"Legacy dispatch contains hours missing from timestamp map: {missing}")
    return merged.rename(columns={id_column: "source"})[["timestamp", "legacy_hour", "source", "heat_kW"]]


def _write_json(path: Path, payload: dict[str, Any]) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def _normalise_solver_report(path: Path, config: dict[str, Any]) -> dict[str, Any]:
    if path.is_file():
        report = json.loads(path.read_text(encoding="utf-8"))
    else:
        report = {}
    return {
        "solver": report.get("solver", config.get("solver", {}).get("name")),
        "termination_condition": report.get("termination_condition", "unknown"),
        "status": report.get("status", "unknown"),
        "acceptable": bool(report.get("acceptable", False)),
        "configured_mip_gap": report.get("configured_mip_gap", config.get("solver", {}).get("mip_gap")),
        "actual_mip_gap": report.get("actual_mip_gap"),
        "runtime_seconds": report.get("runtime_seconds"),
        "solver_threads": report.get("solver_threads", config.get("solver", {}).get("threads")),
        "solver_time_limit_seconds": report.get("solver_time_limit_seconds", config.get("solver", {}).get("time_limit_seconds")),
        "solver_random_seed": report.get("solver_random_seed", config.get("solver", {}).get("random_seed")),
        "actual_mip_gap_note": "null means the selected Pyomo/HiGHS interface did not expose a final gap value in this run.",
    }


def export_standard_results(case_dir: str | Path, legacy_case_dir: str | Path) -> StandardResultExport:
    """Export standardized P0 result tables and QA report."""

    inputs = validate_case_inputs(case_dir)
    legacy_dir = Path(legacy_case_dir).resolve()
    scenario_id = str(inputs.config["scenario_id"])
    expost_dir = legacy_dir / "scenarios" / scenario_id / "expost"
    out = legacy_dir / "standard_results"
    out.mkdir(parents=True, exist_ok=True)

    assumptions = {
        "data_classification": inputs.config.get("data_classification"),
        "is_real_project_data": inputs.config.get("data_classification") != "synthetic_test",
        "input_data_origin": "Generated by tools/legacy_cli/create_minimal_case.py for P0 smoke testing."
        if inputs.config.get("data_classification") == "synthetic_test"
        else "External case input bundle.",
        "hvac_parameter_status": "Synthetic placeholder values; not approved project HVAC parameters."
        if inputs.config.get("data_classification") == "synthetic_test"
        else "See source and assumption_flag columns in technologies.csv.",
        "load_unit": inputs.config.get("units", {}).get("heating_power"),
        "energy_unit": inputs.config.get("units", {}).get("heating_energy"),
        "dhw_input_includes_dhw": inputs.config.get("dhw", {}).get("input_includes_dhw"),
        "adapter_adds_dhw": inputs.config.get("dhw", {}).get("add_in_adapter"),
        "storage_enabled": inputs.config.get("features", {}).get("storage_enabled"),
        "waste_heat_enabled": inputs.config.get("features", {}).get("waste_heat_enabled"),
        "network_simplification": "Legacy Delaunay/MST candidate network; not yet a construction-ready road-constrained network.",
        "p0_tie_break": "The legacy adapter uses a tiny synthetic pumping cost to avoid multiple zero-cost pipe-flow optima in the smoke test.",
        "heat_pump_simplification": "P0 uses fixed_heat_source only; no temperature-dependent heat-pump COP curve is modelled.",
    }
    assumptions_path = out / "assumptions_used.yaml"
    assumptions_path.write_text(yaml.safe_dump(assumptions, allow_unicode=True, sort_keys=False), encoding="utf-8")

    connections = _read_legacy_csv(expost_dir / "DH_Connection.csv").rename(
        columns={"Node": "node_id", "DH Connection": "connected"}
    )
    if "connected" in connections.columns:
        connections["connected"] = pd.to_numeric(connections["connected"], errors="raise").astype(int)
    connections_path = out / "connections.csv"
    connections.to_csv(connections_path, index=False)

    capacities = _read_legacy_csv(expost_dir / "Investment_Decisions.csv")
    capacities_path = out / "capacities.csv"
    capacities.to_csv(capacities_path, index=False)

    pipes = _read_legacy_csv(expost_dir / "Pipe_Connections.csv")
    pipes_path = out / "pipes.csv"
    pipes.to_csv(pipes_path, index=False)

    dispatch = _read_legacy_dispatch(expost_dir / "Heat_Generation_TS.csv", inputs.timestamp_hour_map)
    dispatch_path = out / "dispatch.csv"
    dispatch.to_csv(dispatch_path, index=False)

    costs = _read_legacy_csv(expost_dir / "Economic_Results.csv")
    costs_path = out / "costs.csv"
    costs.to_csv(costs_path, index=False)

    solver_report = _normalise_solver_report(expost_dir / "solver_report.json", inputs.config)
    solver_report_path = out / "solver_report.json"
    _write_json(solver_report_path, solver_report)

    input_total_kWh = float(inputs.loads["heating_kW"].sum())
    source_totals = dispatch.groupby("source", sort=False)["heat_kW"].sum().to_dict()
    generation_total_kWh = float(dispatch["heat_kW"].sum())
    energy_balance_error_kWh = generation_total_kWh - input_total_kWh
    unserved_heat_kWh = max(0.0, input_total_kWh - generation_total_kWh)

    clustered_total_kWh = None
    heat_network_dir = legacy_dir / "scenarios" / scenario_id / "data" / "heat_network"
    clustered_ts_path = heat_network_dir / "Heat_Demand.csv"
    fallback_clustered_ts_path = heat_network_dir / "Cluster_TS.csv"
    if not clustered_ts_path.is_file() and fallback_clustered_ts_path.is_file():
        clustered_ts_path = fallback_clustered_ts_path
    if clustered_ts_path.is_file():
        clustered_ts = pd.read_csv(clustered_ts_path)
        cluster_columns = [column for column in clustered_ts.columns if str(column).startswith("heat_node_")]
        if cluster_columns:
            clustered_total_kWh = float(clustered_ts[cluster_columns].sum().sum())
            hourly_demand = clustered_ts[["hour", *cluster_columns]].copy()
            hourly_demand["demand_kW"] = hourly_demand[cluster_columns].sum(axis=1)
        else:
            hourly_demand = pd.DataFrame()
    else:
        hourly_demand = pd.DataFrame()
    cluster_relative_error = (
        abs(clustered_total_kWh - input_total_kWh) / max(input_total_kWh, 1e-12)
        if clustered_total_kWh is not None
        else None
    )

    hourly_generation = (
        dispatch.groupby(["legacy_hour", "timestamp"], as_index=False)["heat_kW"]
        .sum()
        .rename(columns={"legacy_hour": "hour", "heat_kW": "generation_kW"})
    )
    if not hourly_demand.empty:
        balance_check = hourly_demand[["hour", "demand_kW"]].merge(hourly_generation, on="hour", how="outer")
    else:
        balance_check = hourly_generation.copy()
        balance_check["demand_kW"] = pd.NA
    balance_check["demand_kW"] = pd.to_numeric(balance_check["demand_kW"], errors="coerce")
    balance_check["generation_kW"] = pd.to_numeric(balance_check["generation_kW"], errors="coerce")
    balance_check["balance_error_kW"] = balance_check["generation_kW"] - balance_check["demand_kW"]
    balance_check["unserved_heat_kWh"] = (balance_check["demand_kW"] - balance_check["generation_kW"]).clip(lower=0)
    balance_check = balance_check[["hour", "timestamp", "demand_kW", "generation_kW", "balance_error_kW", "unserved_heat_kWh"]]
    balance_check_path = out / "balance_check.csv"
    balance_check.to_csv(balance_check_path, index=False)
    max_balance_error_kW = float(balance_check["balance_error_kW"].abs().max()) if not balance_check.empty else None

    cost_name_column = costs.columns[0]
    cost_value_column = costs.columns[1]
    cost_values = pd.to_numeric(costs[cost_value_column], errors="raise")
    total_mask = costs[cost_name_column].astype(str).str.contains("total", case=False, na=False)
    reported_total_cost = float(cost_values[total_mask].iloc[0]) if total_mask.any() else None
    recomputed_total_cost = float(cost_values[~total_mask].sum())
    cost_reaggregation_error = (
        recomputed_total_cost - reported_total_cost if reported_total_cost is not None else None
    )
    cost_check = pd.DataFrame(
        [
            {"metric": "reported_total_cost", "value": reported_total_cost},
            {"metric": "recomputed_sum_of_components", "value": recomputed_total_cost},
            {"metric": "reaggregation_error", "value": cost_reaggregation_error},
        ]
    )
    cost_check_path = out / "cost_check.csv"
    cost_check.to_csv(cost_check_path, index=False)

    expected_hours = int(len(inputs.timestamp_hour_map))
    actual_hours = int(dispatch["legacy_hour"].nunique())
    sequential_hours = inputs.timestamp_hour_map["hour"].tolist() == list(range(1, expected_hours + 1))
    qa = inputs.config.get("qa", {})
    checks = {
        "hour_count_matches_config": actual_hours == expected_hours,
        "legacy_hours_are_continuous_1_based": bool(sequential_hours),
        "heating_power_unit_is_kW": inputs.config.get("units", {}).get("heating_power") == "kW",
        "heating_energy_unit_is_kWh": inputs.config.get("units", {}).get("heating_energy") == "kWh",
        "random_seed_is_defined": inputs.config.get("clustering", {}).get("random_seed") is not None,
        "solver_status_is_acceptable": bool(solver_report["acceptable"]),
        "unserved_heat_within_tolerance": unserved_heat_kWh <= float(qa.get("unserved_tolerance_kWh", 1e-6)),
        "energy_balance_within_tolerance": abs(energy_balance_error_kWh)
        <= float(qa.get("balance_tolerance_kW", 1e-6)) * expected_hours,
        "max_hourly_balance_within_tolerance": (
            max_balance_error_kW is not None
            and abs(max_balance_error_kW) <= float(qa.get("balance_tolerance_kW", 1e-6))
        ),
        "cluster_energy_within_tolerance": (
            cluster_relative_error is not None
            and cluster_relative_error <= float(qa.get("cluster_energy_relative_tolerance", 0.001))
        ),
        "cost_components_sum_to_total": (
            cost_reaggregation_error is not None
            and abs(cost_reaggregation_error) <= float(qa.get("cost_tolerance_CNY", 1e-6))
        ),
    }
    qa_report: dict[str, Any] = {
        "case_id": inputs.config["case_id"],
        "scenario_id": scenario_id,
        "contract_version": inputs.config["contract_version"],
        "data_version": inputs.config["data_version"],
        "time": inputs.config["time"],
        "units": inputs.config["units"],
        "random_seed": inputs.config["clustering"]["random_seed"],
        "building_count": int(inputs.buildings.shape[0]),
        "hour_count": expected_hours,
        "input_total_heat_kWh": round(input_total_kWh, 9),
        "legacy_generation_total_heat_kWh": round(generation_total_kWh, 9),
        "source_totals_kWh": {str(key): round(float(value), 9) for key, value in source_totals.items()},
        "energy_balance_error_kWh": round(energy_balance_error_kWh, 9),
        "max_hourly_balance_error_kW": round(max_balance_error_kW, 9) if max_balance_error_kW is not None else None,
        "unserved_heat_kWh": round(unserved_heat_kWh, 9),
        "clustered_total_heat_kWh": round(clustered_total_kWh, 9) if clustered_total_kWh is not None else None,
        "cluster_energy_relative_error": round(float(cluster_relative_error), 12)
        if cluster_relative_error is not None
        else None,
        "solver": solver_report,
        "reported_total_cost": round(reported_total_cost, 9) if reported_total_cost is not None else None,
        "recomputed_total_cost": round(recomputed_total_cost, 9),
        "cost_reaggregation_error": round(cost_reaggregation_error, 9) if cost_reaggregation_error is not None else None,
        "checks": checks,
        "acceptable": bool(all(checks.values())),
    }
    qa_path = out / "qa_report.json"
    _write_json(qa_path, qa_report)

    metadata = {
        "case_id": inputs.config["case_id"],
        "scenario_id": scenario_id,
        "standard_result_version": "p0_v1",
        "source_legacy_case_dir": str(legacy_dir),
        "files": {
            "connections": connections_path.name,
            "assumptions": assumptions_path.name,
            "capacities": capacities_path.name,
            "pipes": pipes_path.name,
            "dispatch": dispatch_path.name,
            "costs": costs_path.name,
            "solver_report": solver_report_path.name,
            "balance_check": balance_check_path.name,
            "cost_check": cost_check_path.name,
            "qa_report": qa_path.name,
        },
        "qa_acceptable": qa_report["acceptable"],
    }
    metadata_path = out / "run_metadata.json"
    _write_json(metadata_path, metadata)

    return StandardResultExport(
        output_dir=out,
        metadata_json=metadata_path,
        assumptions_yaml=assumptions_path,
        connections_csv=connections_path,
        capacities_csv=capacities_path,
        pipes_csv=pipes_path,
        dispatch_csv=dispatch_path,
        costs_csv=costs_path,
        solver_report_json=solver_report_path,
        balance_check_csv=balance_check_path,
        cost_check_csv=cost_check_path,
        qa_report_json=qa_path,
    )
